-- Schemat bazy w chwili wprowadzenia Flyway. Odpowiada temu, co Hibernate tworzył wcześniej
-- automatycznie z encji (ddl-auto), łącznie z nazwami kluczy obcych.
--
-- Istniejąca baza utworzona przez Hibernate nie wykonuje tej migracji: Flyway oznacza ją
-- jako wersję 1 (spring.flyway.baseline-on-migrate) i przechodzi do kolejnych plików.

CREATE TABLE sections (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL UNIQUE,
    sort_order INTEGER      NOT NULL
);

CREATE TABLE breeders (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                            VARCHAR(32)  NOT NULL,
    surname                         VARCHAR(64)  NOT NULL,
    email                           VARCHAR(320) NOT NULL UNIQUE,
    password_hash                   VARCHAR(255) NOT NULL,
    phone_number                    VARCHAR(9)   NOT NULL UNIQUE,
    date_of_birth                   DATE,
    postal_code                     VARCHAR(6),
    city                            VARCHAR(100),
    street                          VARCHAR(100),
    house_number                    VARCHAR(10),
    section_id                      BIGINT       NOT NULL,
    role                            VARCHAR(20)  NOT NULL,
    status                          VARCHAR(255) NOT NULL,
    session_version                 INTEGER      NOT NULL DEFAULT 0,
    password_reset_token_hash       VARCHAR(64),
    password_reset_token_expires_at TIMESTAMP(6) WITH TIME ZONE,
    created_at                      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT breeders_role_check CHECK (role IN ('BREEDER', 'MODERATOR', 'ADMINISTRATOR')),
    CONSTRAINT breeders_status_check CHECK (status IN ('PENDING', 'ACTIVE', 'BLOCKED'))
);

CREATE TABLE announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(150) NOT NULL,
    content    TEXT         NOT NULL,
    is_pinned  BOOLEAN      NOT NULL,
    author_id  BIGINT       NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE board_members (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role               VARCHAR(50) NOT NULL,
    breeder_id         BIGINT,
    custom_name        VARCHAR(32),
    custom_surname     VARCHAR(64),
    contact_phone      VARCHAR(9),
    managed_section_id BIGINT,
    CONSTRAINT board_members_role_check CHECK (role IN ('PREZES', 'WICEPREZES_DS_LOTOWYCH', 'WICEPREZES_DS_FINANSOWYCH',
        'WICEPREZES_DS_GOSPODARCZYCH', 'SEKRETARZ', 'SKARBNIK', 'CZLONEK_ZARZADU'))
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breeder_id BIGINT       NOT NULL,
    message    VARCHAR(500) NOT NULL,
    link       VARCHAR(255),
    type       VARCHAR(255) NOT NULL,
    is_read    BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT notifications_type_check CHECK (type IN ('ACCOUNT_APPROVED', 'ROLE_CHANGED', 'NEW_ANNOUNCEMENT',
        'ANNOUNCEMENT_DELETED', 'NEW_THREAD', 'NEW_REPLY', 'NEW_FLIGHT_PLAN', 'NEW_FLIGHT_RESULT', 'NEW_FOUND_PIGEON_REPORT'))
);

CREATE TABLE forum_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    sort_order  INTEGER,
    author_id   BIGINT       NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE forum_threads (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    category_id  BIGINT       NOT NULL,
    breeder_id   BIGINT       NOT NULL,
    is_pinned    BOOLEAN      NOT NULL,
    is_locked    BOOLEAN      NOT NULL,
    views        INTEGER DEFAULT 0,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_post_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE forum_posts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id  BIGINT NOT NULL,
    breeder_id BIGINT NOT NULL,
    body       TEXT   NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    edited_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE flight_plans (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_year  INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_flight_plans_year UNIQUE (plan_year)
);

CREATE TABLE flight_plan_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_plan_id   BIGINT       NOT NULL,
    pigeon_age_group VARCHAR(20)  NOT NULL,
    scheduled_date   DATE         NOT NULL,
    location         VARCHAR(100) NOT NULL,
    distance_km      INTEGER      NOT NULL,
    category         VARCHAR(30),
    list_type        VARCHAR(100) NOT NULL,
    CONSTRAINT flight_plan_entries_pigeon_age_group_check CHECK (pigeon_age_group IN ('ADULT', 'YOUNG'))
);

CREATE TABLE flight_results (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_plan_entry_id BIGINT       NOT NULL,
    scope                VARCHAR(20)  NOT NULL,
    section_id           BIGINT,
    original_file_name   VARCHAR(255) NOT NULL,
    content              TEXT         NOT NULL,
    uploaded_by          BIGINT       NOT NULL,
    uploaded_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT flight_results_scope_check CHECK (scope IN ('BRANCH', 'SECTION'))
);

CREATE TABLE pigeon_flights (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                      BIGINT           NOT NULL,
    name                          VARCHAR(150)     NOT NULL,
    ring_number                   VARCHAR(32),
    release_site                  VARCHAR(150),
    original_file_name            VARCHAR(255)     NOT NULL,
    start_time                    TIMESTAMP(6) WITH TIME ZONE,
    end_time                      TIMESTAMP(6) WITH TIME ZONE,
    start_latitude                DOUBLE PRECISION NOT NULL,
    start_longitude               DOUBLE PRECISION NOT NULL,
    end_latitude                  DOUBLE PRECISION NOT NULL,
    end_longitude                 DOUBLE PRECISION NOT NULL,
    straight_line_distance_meters DOUBLE PRECISION NOT NULL,
    track_distance_meters         DOUBLE PRECISION NOT NULL,
    duration_seconds              BIGINT           NOT NULL,
    average_speed_m_per_min       DOUBLE PRECISION NOT NULL,
    straight_line_speed_m_per_min DOUBLE PRECISION NOT NULL,
    max_speed_m_per_min           DOUBLE PRECISION NOT NULL,
    min_elevation_meters          DOUBLE PRECISION,
    max_elevation_meters          DOUBLE PRECISION,
    elevation_gain_meters         DOUBLE PRECISION,
    total_points                  INTEGER          NOT NULL,
    timestamps_available          BOOLEAN          NOT NULL,
    uploaded_at                   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE flight_track_points (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id        BIGINT           NOT NULL,
    point_index      INTEGER          NOT NULL,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    elevation_meters DOUBLE PRECISION,
    recorded_at      TIMESTAMP(6) WITH TIME ZONE,
    speed_m_per_min  DOUBLE PRECISION
);

CREATE TABLE found_pigeon_reports (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ring_number            VARCHAR(64)  NOT NULL,
    ring_number_normalized VARCHAR(64)  NOT NULL,
    found_location         VARCHAR(150),
    found_country          VARCHAR(100),
    description            TEXT,
    contact_email          VARCHAR(320),
    contact_phone          VARCHAR(32),
    preferred_language     VARCHAR(2)   NOT NULL,
    status                 VARCHAR(20)  NOT NULL,
    admin_note             TEXT,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT found_pigeon_reports_preferred_language_check CHECK (preferred_language IN ('PL', 'EN', 'DE')),
    CONSTRAINT found_pigeon_reports_status_check CHECK (status IN ('PENDING', 'APPROVED', 'RESOLVED', 'REJECTED'))
);

CREATE INDEX idx_track_point_flight ON flight_track_points (flight_id, point_index);
CREATE INDEX idx_found_pigeon_ring ON found_pigeon_reports (ring_number_normalized);
CREATE INDEX idx_found_pigeon_status ON found_pigeon_reports (status);

